import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash, randomUUID } from 'node:crypto';
import { createCollaboration } from '../server/collaboration.mjs';
import { createServer } from '../server/index.mjs';
import { configFromEnv } from '../server/assistant.mjs';

const root = path.resolve('test-results/collaboration'); fs.mkdirSync(root, { recursive: true });
const password = 'fixture-password-only';
test('real multi-user API: live sync, file round-trip, permissions, pins, broadcasts and restart persistence', async t => {
  const directory = fs.mkdtempSync(path.join(root, 'db-'));
  let service = createCollaboration(directory), server, base;
  const ids = [];
  for (const [username, name, role] of [['admin', '管理员', 'admin'], ['teacher1', '林老师', 'member'], ['teacher2', '周老师', 'member']]) ids.push(await service.addUser({ username, name, role, password }));
  const group = service.setupRoom('学院工作群', ids[0], ids);
  const start = async () => { server = createServer(configFromEnv({}), fetch, service); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); base = `http://127.0.0.1:${server.address().port}`; };
  const stop = async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); service.close(); };
  t.after(async () => { await stop(); assert.ok(directory.startsWith(root + path.sep)); fs.rmSync(directory, { recursive: true, force: true }); });
  await start();
  async function request(route, token, body) { return fetch(base + '/api/collab' + route, { method: body === undefined ? 'GET' : 'POST', headers: { Origin: base, ...(token ? { Authorization: 'Bearer ' + token } : {}), ...(body === undefined ? {} : { 'Content-Type': 'application/json' }) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) }); }
  const login = async username => { const response = await request('/login', '', { username, password }); assert.equal(response.status, 200); return (await response.json()).token; };
  let admin = await login('admin'), first = await login('teacher1'), second = await login('teacher2');
  assert.equal((await request('/state', '')).status, 401);
  assert.equal((await request('/login', '', { username: 'teacher1', password: 'incorrect-password' })).status, 401);
  const initial = await (await request('/state', second)).json(); assert.equal(initial.rooms.length, 1); assert.equal(initial.contacts.length, 3);
  assert.ok(!JSON.stringify(initial).includes(password)); assert.ok(!JSON.stringify(initial).includes('salt'));
  const pending = request(`/sync?after=${initial.revision}`, second);
  const body = { room: group, content: '这是一条真实持久化消息', files: [], clientId: randomUUID() };
  const sent = await request('/messages', first, body); assert.equal(sent.status, 201); const message = await sent.json();
  assert.equal((await pending).status, 200);
  const received = await (await request(`/rooms/${group}/messages`, second)).json(); assert.equal(received.items[0].content, body.content);
  const repeated = await request('/messages', first, body); assert.equal(repeated.status, 200); assert.equal((await repeated.json()).id, message.id);
  assert.equal((await request('/messages', first, { ...body, content: 'different content' })).status, 409);
  assert.equal((await request('/messages/pin', first, { id: message.id, pinned: true })).status, 403);
  assert.equal((await request('/messages/pin', admin, { id: message.id, pinned: true })).status, 200);
  const pinned = await (await request(`/rooms/${group}/messages`, second)).json(); assert.equal(pinned.pins[0].id, message.id);
  assert.equal((await (await request('/state', second)).json()).rooms[0].unread, 1);
  assert.equal((await request('/read', second, { room: group, lastId: message.id })).status, 200);
  assert.equal((await (await request('/state', second)).json()).rooms[0].unread, 0);
  const privateRoom = await (await request('/rooms', first, { kind: 'private', members: [ids[2]] })).json();
  const same = await (await request('/rooms', second, { kind: 'private', members: [ids[1]] })).json(); assert.equal(same.id, privateRoom.id);
  assert.equal((await request(`/rooms/${privateRoom.id}/messages`, admin)).status, 403);
  const bytes = Buffer.from('资料传输测试\n真实文件内容\n' + 'test'.repeat(1000));
  const upload = await fetch(`${base}/api/collab/files?room=${privateRoom.id}&name=${encodeURIComponent('课程建设资料.txt')}`, { method: 'POST', headers: { Authorization: 'Bearer ' + first, 'Content-Type': 'application/octet-stream' }, body: bytes });
  assert.equal(upload.status, 201); const file = await upload.json();
  assert.equal((await request(`/files/${file.id}`, second)).status, 403);
  await new Promise(resolve => setTimeout(resolve, 210));
  assert.equal((await request('/messages', first, { room: privateRoom.id, content: '请查收附件', files: [file.id], clientId: randomUUID() })).status, 201);
  const download = await request(`/files/${file.id}`, second); assert.equal(download.status, 200);
  assert.equal(createHash('sha256').update(Buffer.from(await download.arrayBuffer())).digest('hex'), createHash('sha256').update(bytes).digest('hex'));
  assert.equal((await request(`/files/${file.id}`, admin)).status, 403);
  const wrongRoom = await request('/messages', admin, { room: group, content: '', files: [file.id], clientId: randomUUID() }); assert.equal(wrongRoom.status, 403);
  const noticeBody = { title: '资料提交提醒', content: '请各位老师核对本周归档资料。', clientId: randomUUID() };
  assert.equal((await request('/broadcasts', first, noticeBody)).status, 403);
  const notice = await request('/broadcasts', admin, noticeBody); assert.equal(notice.status, 201); const noticeId = (await notice.json()).id;
  assert.equal((await request('/broadcasts', admin, noticeBody)).status, 200);
  assert.equal((await request('/broadcasts/pin', first, { id: noticeId, pinned: true })).status, 403);
  assert.equal((await request('/broadcasts/pin', admin, { id: noticeId, pinned: true })).status, 200);
  let snapshot = await (await request('/state', second)).json(); assert.equal(snapshot.broadcasts[0].pinned, 1); assert.equal(snapshot.broadcasts[0].isRead, 0);
  assert.equal((await request('/broadcasts/read', second, { id: noticeId })).status, 200);
  snapshot = await (await request('/state', second)).json(); assert.equal(snapshot.broadcasts[0].isRead, 1);
  await request('/logout', first, {}); assert.equal((await request('/state', first)).status, 401);
  await stop(); service = createCollaboration(directory); await start();
  assert.equal((await request('/state', second)).status, 401);
  second = await login('teacher2');
  const persisted = await (await request(`/rooms/${privateRoom.id}/messages`, second)).json(); assert.equal(persisted.items[0].files[0].name, file.name);
  assert.equal((await request(`/files/${file.id}`, second)).status, 200);
  snapshot = await (await request('/state', second)).json(); assert.equal(snapshot.broadcasts[0].title, noticeBody.title); assert.equal(snapshot.broadcasts[0].isRead, 1);
});
